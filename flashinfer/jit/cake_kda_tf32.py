def _key(args, kwargs):
    return (tuple(args), tuple(sorted(kwargs.items())))


def _source_path(relative):
    installed = jit_env.FLASHINFER_CSRC_DIR / Path(relative).relative_to('csrc')
    if installed.is_file():
        return installed
    return Path(__file__).resolve().parents[2] / relative


@cache
def spec(name):
    record = MODULES[name]
    include = jit_env.FLASHINFER_INCLUDE_DIR
    if not include.is_dir():
        include = Path(__file__).resolve().parents[2] / 'include'
    sources = [_source_path(path) for path in record['sources']]
    return gen_jit_spec(
        name=record['cache_name'], sources=sources,
        extra_cuda_cflags=[*sm103a_nvcc_flags, *record['compile_flags']],
        extra_include_paths=[sources[-1].parent, _source_path('csrc/tvm_ffi_utils.h').parent, include],
    )


@cache
def load(name):
    return spec(name).build_and_load()


class PreparedKernel:
    """A native module plus caller-retained pointer-TMA descriptor storage."""
    def __init__(self, name):
        record = MODULES[name]
        self.name = name
        self.schedule = None
        native = load(name)
        entry = record['ffi_entry']
        self._call = getattr(native, entry + '_prepared' if record['tma_workspace_bytes'] else entry)
        self._prepare = getattr(native, entry + '_prepare_tma') if record['tma_workspace_bytes'] else None
        self._ready = self._prepare is None
        self._arg_plan = record['arg_plan']
        self.descriptor_storage = torch.empty(record['tma_workspace_bytes'], dtype=torch.uint8, device='cuda')

    def _arguments(self, grid, bindings):
        grid = tuple(grid) + (1,) * (3 - len(grid))
        args = []
        for kind, name in self._arg_plan:
            if kind == 'grid':
                args.append(grid[('grid_x', 'grid_y', 'grid_z').index(name)])
            elif kind == 'workspace':
                args.append(self.descriptor_storage)
            else:
                args.append(bindings[name])
        return args

    def prepare(self, *, grid, **bindings):
        if self._prepare is not None:
            self._prepare(*self._arguments(grid, bindings))
        self._ready = True

    def launch(self, *, grid, **bindings):
        if not self._ready:
            raise RuntimeError('TMA descriptors must be initialized during preparation')
        return self._call(*self._arguments(grid, bindings))


def prepare_descriptors(prepared):
    """Initialize each caller-owned descriptor workspace without running KDA.

    Prepared tensor addresses and metadata are immutable. Tensor contents may
    change between calls. As with the input tensors, callers must order use on
    another stream after preparation on the current stream.
    """
    import tvm_ffi
    owner = getattr(prepared, '_impl', prepared)
    with tvm_ffi.use_torch_stream():
        if hasattr(owner, '_main'):
            for child in (owner._main, owner._map, owner._correction):
                if child is not None:
                    prepare_descriptors(child)
            if owner._use_output_projection:
                owner._projection_module.prepare(grid=owner._projection_grid, **owner._projection_args)
        else:
            if owner.prepare_module is not None:
                owner.prepare_module.prepare(grid=owner.prepare_grid, **owner.prepare_args)
            owner.module.prepare(grid=owner.grid, **owner.args)


def _factory(name, *args, **kwargs):
    if torch.cuda.get_device_capability() != (10, 3):
        raise NotImplementedError('TF32 KDA export requires SM103a')
    variants = FACTORIES.get(name, {})
    key = _key(args, kwargs)
    if key not in variants:
        raise NotImplementedError(f'Unexported TF32 KDA schedule specialization: {(name, *key)}')
    return PreparedKernel(variants[key])
